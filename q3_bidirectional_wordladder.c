/* Q3: Bidirectional BFS for the shortest transformation sequence in a word
   graph. The graph is implicit: neighbours of a word are generated by
   changing one letter and looking the candidate up in a hash table. */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#define MAXL 12
typedef unsigned long long u64;

static char (*Wd)[MAXL];
static u64 *H, pw[MAXL];
static int *tab, mask, L;

static u64 hashw(const char *s) {          /* sum (c - 'a' + 1) * 131^i */
    u64 h = 0;
    int i;
    for (i = 0; i < L; i++) h += (u64)(s[i] - 'a' + 1) * pw[i];
    return h;
}
static unsigned slot(u64 h) {
    return (unsigned)((h * 0x9E3779B97F4A7C15ULL) >> 40) & mask;
}
static int findWord(u64 h, const char *s) {
    unsigned i = slot(h);
    while (tab[i]) {
        int id = tab[i] - 1;
        if (H[id] == h && memcmp(Wd[id], s, L) == 0) return id;
        i = (i + 1) & mask;
    }
    return -1;
}
static void insertWord(int id) {
    unsigned i = slot(H[id]);
    while (tab[i]) i = (i + 1) & mask;
    tab[i] = id + 1;
}
static int validWord(const char *s) {
    int i;
    if ((int)strlen(s) != L) return 0;
    for (i = 0; i < L; i++) if (s[i] < 'a' || s[i] > 'z') return 0;
    return 1;
}

int main(void) {
    int N, i, sz = 1, cnt = 0;
    char buf[64], a[64], b[64];
    printf("Enter dictionary size N and word length L: ");
    if (scanf("%d %d", &N, &L) != 2 || N < 1 || N > 100000 || L < 1 || L > 10) {
        printf("Invalid input.\n");
        return 1;
    }
    Wd = malloc((N + 1) * sizeof(*Wd));
    H = malloc((N + 1) * sizeof(u64));
    while (sz < 2 * (N + 1)) sz <<= 1;
    tab = calloc(sz, sizeof(int));
    mask = sz - 1;
    pw[0] = 1;
    for (i = 1; i < MAXL; i++) pw[i] = pw[i - 1] * 131;
    printf("Enter the %d dictionary words: ", N);
    for (i = 0; i < N; i++) {
        u64 h;
        if (scanf("%63s", buf) != 1 || !validWord(buf)) {
            printf("Invalid word.\n");
            return 1;
        }
        h = hashw(buf);
        if (findWord(h, buf) >= 0) continue;   /* ignore duplicates */
        memcpy(Wd[cnt], buf, L + 1); H[cnt] = h; insertWord(cnt); cnt++;
    }
    printf("Enter start word A and target word B: ");
    if (scanf("%63s %63s", a, b) != 2 || !validWord(a) || !validWord(b)) {
        printf("Invalid word.\n");
        return 1;
    }
    if (strcmp(a, b) == 0) { printf("Minimum number of mutations: 0\n"); goto end; }
    int idB = findWord(hashw(b), b);
    if (idB < 0) { printf("Minimum number of mutations: -1 (B is not in D)\n"); goto end; }
    int idA = findWord(hashw(a), a);
    if (idA < 0) {                              /* A need not be in D */
        memcpy(Wd[cnt], a, L + 1); H[cnt] = hashw(a); insertWord(cnt); idA = cnt++;
    }
    int *dist[2], *fr[2], *nx[2], fn[2], s;
    for (s = 0; s < 2; s++) {
        dist[s] = malloc(cnt * sizeof(int));
        fr[s] = malloc(cnt * sizeof(int));
        nx[s] = malloc(cnt * sizeof(int));
        for (i = 0; i < cnt; i++) dist[s][i] = -1;
    }
    dist[0][idA] = 0; fr[0][0] = idA; fn[0] = 1;
    dist[1][idB] = 0; fr[1][0] = idB; fn[1] = 1;
    int best = 1 << 30;
    while (fn[0] && fn[1]) {
        int sd = fn[0] <= fn[1] ? 0 : 1, o = 1 - sd, nn = 0, k, pos;
        for (k = 0; k < fn[sd]; k++) {          /* expand the smaller frontier */
            int u = fr[sd][k];
            char w[MAXL];
            memcpy(w, Wd[u], L + 1);
            for (pos = 0; pos < L; pos++) {
                char c = w[pos], ch;
                for (ch = 'a'; ch <= 'z'; ch++) {
                    u64 h2;
                    int v;
                    if (ch == c) continue;
                    h2 = H[u] + (u64)(long long)(ch - c) * pw[pos];
                    w[pos] = ch;
                    v = findWord(h2, w);
                    if (v >= 0) {
                        if (dist[o][v] >= 0) {  /* frontiers meet */
                            int t = dist[sd][u] + 1 + dist[o][v];
                            if (t < best) best = t;
                        } else if (dist[sd][v] < 0) {
                            dist[sd][v] = dist[sd][u] + 1;
                            nx[sd][nn++] = v;
                        }
                    }
                }
                w[pos] = c;
            }
        }
        if (best < (1 << 30)) {
            printf("Minimum number of mutations: %d\n", best);
            goto end;
        }
        { int *t = fr[sd]; fr[sd] = nx[sd]; nx[sd] = t; fn[sd] = nn; }
    }
    printf("Minimum number of mutations: -1 (no valid transformation)\n");
end:
    printf("Time complexity: O(N * 25 * L) probes (O(N*L^2) worst); space: O(N*L).\n");
#ifdef _WIN32
    system("pause");
#endif
    return 0;
}
